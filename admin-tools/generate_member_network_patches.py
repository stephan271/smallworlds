#!/usr/bin/env python3
"""Put an overlay's member applications on the Member Network, or take them off.

With the Member Network on (docs/adr/0066), each member application includes
its Component from infrastructure/kubernetes/components/member-network: the
full application moves to the `members` entrypoint and only its Guest Paths
stay public. The member Headscale (tenants/member-network) gets the hostnames
its DNS answers with the Member Gateway, and the URLs it is reached at.

Everything written lives between marker comments, so a re-run replaces it and
`--mode off` removes it again:

- the `components:` list, as the first lines of the file (a key that has to
  stay out of the `patches:` list, which the other generators append to);
- the patches, inside `patches:`, like generate_storage_patches.py.

The root kustomization's Application for member-network is added by
prepare-community-repo.sh like any selected application's; `--app root --mode
off` removes it.

Plain Immich has no recorded Guest Paths, so the Member Network refuses it
(`--check`): only Gallery may be the photo application. Nextcloud's Guest
Paths were recorded with Euro-Office; Collabora's paths inside Nextcloud were
not, so it is refused too.
"""
import argparse
import re
import sys
from pathlib import Path

MODES = ("off", "on")

BASE_URL = "https://github.com/stephan271/smallworlds.git/infrastructure/kubernetes"

COMPONENTS_BEGIN = "# >>> smallworlds:member-network — generated by prepare-community-repo.sh, do not edit"
COMPONENTS_END = "# <<< smallworlds:member-network"
PATCHES_BEGIN = "  # >>> smallworlds:member-network-patches — generated by prepare-community-repo.sh, do not edit"
PATCHES_END = "  # <<< smallworlds:member-network-patches"

# The Component each member application includes. Applications not listed
# (Jitsi, the Office editors, Keycloak, join, Headscale) stay public; join only
# learns the member Headscale's address, for its done page.
COMPONENT_BY_APP = {
    "nextcloud": "nextcloud",
    "immich": "gallery",          # only with Gallery, see check()
    "forgejo": "members-only",
    "excalidraw": "members-only",
    "dashboard": "members-only",
    "pod-gateway": "members-only",
    "bulwark": "members-only",
    "stalwart": "stalwart",
}

# The hostname each one answers on; the member Headscale's DNS sends these to
# the Member Gateway. Mirrors the subdomain maps (generate_domain_patches.py,
# main.tf, plan.py, dns_subdomains in smallworlds-init.sh).
SUBDOMAIN_BY_APP = {
    "nextcloud": "files",
    "immich": "photos",
    "forgejo": "git",
    "excalidraw": "whiteboard",
    "dashboard": "dashboard",
    "pod-gateway": "pod",
    "bulwark": "webmail",
    "stalwart": "mail",
}


class MemberNetworkError(Exception):
    pass


def check(mode, apps, photo_backend):
    """Refuse a combination the Member Network cannot serve."""
    if mode not in MODES:
        raise MemberNetworkError(f"unknown mode {mode!r}: choose off or on")
    if mode == "on" and "immich" in apps and photo_backend != "gallery":
        raise MemberNetworkError(
            "the Member Network needs Gallery as the photo application. Plain Immich's "
            "share links have not been recorded, so it cannot tell which of its paths "
            "guests need (docs/adr/0066). Choose gallery, or leave the Member Network off.")
    if mode == "on" and "collabora" in apps:
        raise MemberNetworkError(
            "the Member Network cannot run with Collabora yet. Nextcloud's share links "
            "were recorded with Euro-Office; with Collabora a guest could open a shared "
            "document only as far as Nextcloud's own pages (docs/adr/0066). Choose "
            "euro-office or no Office editor, or leave the Member Network off.")


def host(subdomain, domain, ext):
    return f"{subdomain}{ext}.{domain}"


def member_hosts(apps, domain, ext):
    """The member hostnames, in a fixed order, for the applications deployed."""
    deployed = set(apps) | {"dashboard"}  # the dashboard is always installed
    return [host(SUBDOMAIN_BY_APP[app], domain, ext)
            for app in SUBDOMAIN_BY_APP if app in deployed]


def components_block(app, version):
    component = COMPONENT_BY_APP.get(app)
    if component is None:
        return ""
    return (f"{COMPONENTS_BEGIN}\n"
            "# The Member Network (docs/adr/0066): the full application on `members`,\n"
            "# only its Guest Paths in public.\n"
            "components:\n"
            f"  - {BASE_URL}/components/member-network/{component}?ref={version}\n"
            f"{COMPONENTS_END}\n")


def patches_block(app, apps, domain, ext):
    if app == "nextcloud":
        files = host("files", domain, ext)
        body = f"""\
  - target:
      kind: Ingress
      name: nextcloud-guest
    patch: |-
      - op: replace
        path: /spec/rules/0/host
        value: {files}
      - op: replace
        path: /spec/tls/0/hosts/0
        value: {files}
"""
    elif app == "member-network":
        network = host("network", domain, ext)
        identity = host("identity", domain, ext)
        hosts = "\n".join(f"                      {name}" for name in member_hosts(apps, domain, ext))
        body = f"""\
  - target:
      kind: Ingress
      name: member-headscale
    patch: |-
      - op: replace
        path: /spec/rules/0/host
        value: {network}
      - op: replace
        path: /spec/tls/0/hosts/0
        value: {network}
  - target:
      kind: Job
      name: keycloak-client-init
    patch: |-
      - op: replace
        path: /spec/template/spec/containers/0/env/0/value
        value: '["https://{network}/oidc/callback"]'
  - target:
      kind: Deployment
      name: headscale
    patch: |-
      apiVersion: apps/v1
      kind: Deployment
      metadata:
        name: headscale
      spec:
        template:
          spec:
            initContainers:
              - name: dns-records
                env:
                  - name: MEMBER_HOSTS
                    value: >-
{hosts}
            containers:
              - name: headscale
                env:
                  - name: HEADSCALE_SERVER_URL
                    value: https://{network}
                  - name: HEADSCALE_OIDC_ISSUER
                    value: https://{identity}/realms/smallworlds
"""
    elif app == "join":
        # The done page shows how to connect a device to the Member Network.
        body = f"""\
  - target:
      kind: ConfigMap
      name: join-config
    patch: |-
      - op: add
        path: /data/MEMBER_NETWORK_URL
        value: https://{host("network", domain, ext)}
"""
    else:
        return ""
    return f"{PATCHES_BEGIN}\n{body}{PATCHES_END}\n"


def _strip(content, begin, end):
    pattern = re.compile(
        r"^" + re.escape(begin.split(" — ")[0]) + r".*?^" + re.escape(end) + r"\n",
        re.MULTILINE | re.DOTALL)
    return pattern.sub("", content)


def strip_blocks(content):
    return _strip(_strip(content, COMPONENTS_BEGIN, COMPONENTS_END), PATCHES_BEGIN, PATCHES_END)


def render(content, components, patches):
    """`content` with the generated blocks replaced by these (empty = removed)."""
    content = strip_blocks(content)
    if components:
        if re.search(r"(?m)^components:", content):
            raise MemberNetworkError(
                "this kustomization already has a `components:` list of its own. Move its "
                "entries into the generated block's place by hand, or remove them, and run "
                "again.")
        content = components + content
    if patches:
        if not content.endswith("\n"):
            content += "\n"
        if not re.search(r"(?m)^patches:", content):
            content += "\npatches:\n"
        content += patches
    return content


def remove_root_application(content):
    """Drop the member-network Application and its routing from the root."""
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    from reconcile_office_selection import remove_application
    return remove_application(content, "member-network")


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--app", required=True,
                        help='tenant directory, "member-network", or "root" for the overlay root')
    parser.add_argument("--mode", required=True, choices=MODES)
    parser.add_argument("--apps", default="",
                        help="the selected optional applications, separated by spaces")
    parser.add_argument("--photo-backend", default="immich", choices=("immich", "gallery"))
    parser.add_argument("--domain", default="smallworlds.network")
    parser.add_argument("--ext", default="")
    parser.add_argument("--version", default="main", help="the ref the Component URLs pin")
    parser.add_argument("--kustomization-file")
    parser.add_argument("--check", action="store_true", help="only validate; write nothing")
    args = parser.parse_args()
    apps = args.apps.split()

    try:
        check(args.mode, apps, args.photo_backend)
    except MemberNetworkError as error:
        print(f"Error: {error}", file=sys.stderr)
        return 2
    if args.check:
        return 0
    if not args.kustomization_file:
        parser.error("--kustomization-file is required unless --check is given")

    path = Path(args.kustomization_file)
    original = path.read_text(encoding="utf-8")
    if args.app == "root":
        updated = original if args.mode == "on" else remove_root_application(original)
    else:
        on = args.mode == "on"
        components = components_block(args.app, args.version) if on else ""
        patches = patches_block(args.app, apps, args.domain, args.ext) if on else ""
        try:
            updated = render(original, components, patches)
        except MemberNetworkError as error:
            print(f"Error: {path}: {error}", file=sys.stderr)
            return 2
    if updated != original:
        path.write_text(updated, encoding="utf-8")
        print(f"Member Network ({args.mode}): updated {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
