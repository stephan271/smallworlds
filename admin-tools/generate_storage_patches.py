#!/usr/bin/env python3
"""Point an overlay at an external S3 provider instead of the in-cluster Garage.

Most consumers need nothing from here: endpoint, region and bucket travel in
the same Secret as the key (bases/garage-init-job writes them), so the rclone
jobs, Forgejo and Plane follow whatever that Secret says. What is left are the
places where the value is a literal field of a resource and cannot be read from
a Secret — the barman ObjectStore, Velero's BackupStorageLocation, Nextcloud's
chart-rendered environment, the pod-gateway ConfigMap — plus the Applications
that have no business existing without Garage. Those are patched here.

The patches live between two marker comments so a re-run replaces them instead
of appending a second copy, and choosing Garage again removes them.

See docs/adr/0053-object-storage-is-in-house-or-external.md.
"""
import argparse
import re
import sys
import textwrap
from urllib.parse import urlsplit

MODES = ("garage", "external")

BEGIN = "  # >>> smallworlds:object-storage — generated by prepare-community-repo.sh, do not edit"
END = "  # <<< smallworlds:object-storage"

# Tenants whose database backs up into the shared postgres-backups bucket.
# Keycloak keeps a bucket of its own (tenants/keycloak/garage-init-job.yaml).
SHARED_OBJECTSTORE_APPS = ("nextcloud", "immich", "forgejo", "plane", "stalwart")

# Gone when there is no Garage: the two instances, and the replicator whose
# only job is to carry garage-backup offsite — with an external provider the
# Recovery Points are offsite from the moment they are written.
GARAGE_ONLY_APPLICATIONS = ("garage", "garage-backup", "backup-replicator")
GARAGE_ONLY_VOLUMES = ("garage-data-pv", "garage-backup-data-pv", "garage-backup-meta-pv")

# Longest suffix the init jobs append is "-postgres-backups-keycloak" (26), and
# a bucket name may be 63 characters.
PREFIX_PATTERN = re.compile(r"^[a-z0-9](?:[a-z0-9-]{1,28}[a-z0-9])$")


class StorageConfigError(ValueError):
    """An answer that cannot describe a usable S3 endpoint."""


def parse_endpoint(endpoint):
    """Split an endpoint URL into what the differently-shaped consumers want.

    Returns (url, host, port, ssl). Refuses anything with a path or query:
    every consumer here addresses buckets path-style under the bare endpoint,
    and a pasted bucket URL would silently become part of each object key.
    """
    parts = urlsplit(endpoint.strip())
    if parts.scheme not in ("http", "https") or not parts.hostname:
        raise StorageConfigError(
            f"'{endpoint}' is not an S3 endpoint URL — expected something like https://s3.example.com")
    if parts.path not in ("", "/") or parts.query or parts.fragment:
        raise StorageConfigError(
            f"'{endpoint}' has a path — give the provider's endpoint only, without a bucket")
    ssl = parts.scheme == "https"
    port = parts.port or (443 if ssl else 80)
    url = f"{parts.scheme}://{parts.hostname}" + (f":{parts.port}" if parts.port else "")
    return url, parts.hostname, port, ssl


def validate_prefix(prefix):
    if not PREFIX_PATTERN.match(prefix or ""):
        raise StorageConfigError(
            f"'{prefix}' is not a usable bucket prefix — 3 to 30 characters, "
            "lowercase letters, digits and hyphens, starting and ending with a letter or digit")
    return prefix


def bucket_names(prefix, tenant=None):
    """The bucket names the init jobs create. Keep in step with
    bases/garage-init-job, bases/velero-garage-init-job and
    tenants/keycloak/garage-init-job.yaml — admin-tools/test-object-storage.py
    runs those scripts and compares."""
    names = {
        "postgres": f"{prefix}-postgres-backups",
        "postgres-keycloak": f"{prefix}-postgres-backups-keycloak",
        "velero": f"{prefix}-velero-backups",
    }
    if tenant:
        names["tenant"] = f"{prefix}-{tenant}"
        names["tenant-backup"] = f"{prefix}-{tenant}-backup"
    return names


def _objectstore_patch(name, bucket, endpoint_url, region):
    return textwrap.dedent(f"""\
      - target:
          kind: ObjectStore
          name: {name}
        patch: |-
          - op: replace
            path: /spec/configuration/destinationPath
            value: s3://{bucket}/
          - op: replace
            path: /spec/configuration/endpointURL
            value: {endpoint_url}
          - op: replace
            path: /spec/instanceSidecarConfiguration/env
            value:
              - name: AWS_REGION
                value: {region}
              - name: AWS_DEFAULT_REGION
                value: {region}
    """)


def generate_patches(app, primary, backup, prefix):
    """Patches for one overlay kustomization. `primary` and `backup` are
    (endpoint, region) pairs; `app` is a tenant name or "root"."""
    validate_prefix(prefix)
    p_url, p_host, p_port, p_ssl = parse_endpoint(primary[0])
    b_url, _, _, _ = parse_endpoint(backup[0])
    p_region, b_region = primary[1], backup[1]
    if not p_region or not b_region:
        raise StorageConfigError("a region is required — most providers document one, e.g. eu-central-1")
    names = bucket_names(prefix, app)
    patches = ""

    if app in SHARED_OBJECTSTORE_APPS:
        patches += _objectstore_patch("postgres-backups", names["postgres"], b_url, b_region)
    if app == "keycloak":
        patches += _objectstore_patch("postgres-backups-keycloak", names["postgres-keycloak"], b_url, b_region)

    if app == "nextcloud":
        patches += textwrap.dedent(f"""\
          - target:
              kind: Deployment
              name: nextcloud
            patch: |-
              apiVersion: apps/v1
              kind: Deployment
              metadata:
                name: nextcloud
              spec:
                template:
                  spec:
                    containers:
                      - name: nextcloud
                        env:
                          - name: OBJECTSTORE_S3_HOST
                            value: "{p_host}"
                          - name: OBJECTSTORE_S3_PORT
                            value: "{p_port}"
                          - name: OBJECTSTORE_S3_SSL
                            value: "{str(p_ssl).lower()}"
                          - name: OBJECTSTORE_S3_REGION
                            value: "{p_region}"
                          - name: OBJECTSTORE_S3_BUCKET
                            value: "{names['tenant']}"
        """)

    if app == "pod-gateway":
        # The pod archive is a Recovery Point, so it sits on the backup side
        # (the base patches TENANT_BUCKET_NAMESPACE accordingly).
        patches += textwrap.dedent(f"""\
          - target:
              kind: ConfigMap
              name: pod-gateway-config
            patch: |-
              - op: replace
                path: /data/S3_ENDPOINT
                value: "{b_url}"
              - op: replace
                path: /data/S3_REGION
                value: "{b_region}"
              - op: replace
                path: /data/S3_BUCKET
                value: "{names['tenant']}"
        """)

    if app == "root":
        for application in GARAGE_ONLY_APPLICATIONS:
            patches += textwrap.dedent(f"""\
              - target:
                  group: argoproj.io
                  kind: Application
                  name: {application}
                patch: |-
                  $patch: delete
                  apiVersion: argoproj.io/v1alpha1
                  kind: Application
                  metadata:
                    name: {application}
            """)
        for volume in GARAGE_ONLY_VOLUMES:
            patches += textwrap.dedent(f"""\
              - target:
                  kind: PersistentVolume
                  name: {volume}
                patch: |-
                  $patch: delete
                  apiVersion: v1
                  kind: PersistentVolume
                  metadata:
                    name: {volume}
            """)
        # Velero is a core app: its Application points at the upstream tenant
        # directory rather than at an overlay one, so the patch has to ride on
        # the Application itself.
        patches += textwrap.dedent(f"""\
          - target:
              group: argoproj.io
              kind: Application
              name: velero
            patch: |-
              - op: add
                path: /spec/source/kustomize
                value:
                  patches:
                    - target:
                        kind: BackupStorageLocation
                        name: default
                      patch: |-
                        - op: replace
                          path: /spec/objectStorage/bucket
                          value: {names['velero']}
                        - op: replace
                          path: /spec/config/region
                          value: {b_region}
                        - op: replace
                          path: /spec/config/s3Url
                          value: {b_url}
        """)

    return textwrap.indent(patches, "  ")


def strip_block(content):
    """Remove a previously generated block, markers included."""
    pattern = re.compile(
        r"^" + re.escape(BEGIN.split(" — ")[0]) + r".*?^" + re.escape(END) + r"\n",
        re.MULTILINE | re.DOTALL)
    return pattern.sub("", content)


def apply_to_kustomization(path, patches):
    """Replace the generated block in `path` with `patches` (empty = remove)."""
    with open(path, "r", newline="\n") as handle:
        original = handle.read()
    content = strip_block(original)
    if patches:
        if not content.endswith("\n"):
            content += "\n"
        if not re.search(r"(?m)^patches:", content):
            content += "\npatches:\n"
        content += f"{BEGIN}\n{patches}{END}\n"
    if content != original:
        with open(path, "w", newline="\n") as handle:
            handle.write(content)
    return content != original


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--app", required=True, help='tenant name, or "root" for the overlay root')
    parser.add_argument("--mode", required=True, choices=MODES)
    parser.add_argument("--kustomization-file")
    parser.add_argument("--check", action="store_true",
                        help="only validate the answers; write nothing")
    parser.add_argument("--endpoint", default="")
    parser.add_argument("--region", default="")
    parser.add_argument("--bucket-prefix", default="")
    parser.add_argument("--backup-endpoint", default="",
                        help="where Recovery Points go; defaults to --endpoint")
    parser.add_argument("--backup-region", default="")
    args = parser.parse_args()
    if not args.check and not args.kustomization_file:
        parser.error("--kustomization-file is required unless --check is given")

    patches = ""
    if args.mode == "external":
        primary = (args.endpoint, args.region)
        backup = (args.backup_endpoint or args.endpoint, args.backup_region or args.region)
        try:
            patches = generate_patches(args.app, primary, backup, args.bucket_prefix)
        except StorageConfigError as error:
            print(f"Error: {error}", file=sys.stderr)
            return 2
    if args.check:
        return 0

    if apply_to_kustomization(args.kustomization_file, patches):
        print(f"Object storage ({args.mode}): updated {args.kustomization_file}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
